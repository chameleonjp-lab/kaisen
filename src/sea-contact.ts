/**
 * Earliest airframe/water contact over the authoritative position segment and
 * shortest quaternion arc. A curvature bound subdivides possible crossings,
 * so a wing/nose can enter and leave the water between clear endpoint poses.
 * This is intentionally independent of render cadence and decorative time.
 */
export function aircraftSeaContact(
  plane: AircraftPose, previousQuaternion: Quaternion,
  previousTime: number, currentTime: number,
): SeaContact | null {
  if (!Number.isFinite(previousTime) || !Number.isFinite(currentTime) || currentTime < previousTime)
    throw new RangeError('Sea contact needs ordered finite simulation times');
  // Every local point stays inside this rotation-invariant bound, also during
  // the sweep. The position interpolation cannot go below its endpoints.
  if (Math.min(plane.previous.y, plane.position.y) - AIRFRAME_CONTACT_RADIUS > OCEAN_MAX_HEIGHT + SEA_CONTACT_TOLERANCE)
    return null;

  const q0 = previousQuaternion.clone().normalize(), q1 = plane.quaternion.clone().normalize();
  const angle = q0.angleTo(q1), rotationReach = AIRFRAME_CONTACT_RADIUS * angle;
  const dx = plane.position.x - plane.previous.x;
  const dy = plane.position.y - plane.previous.y;
  const dz = plane.position.z - plane.previous.z;
  const duration = currentTime - previousTime;
  const matrix = new Matrix4(), rotation = new Quaternion();
  // Upper bound on each vertex's clearance second derivative with respect to
  // fraction (not seconds): rigid rotation acceleration + sinusoidal waves.
  let curvature = AIRFRAME_CONTACT_RADIUS * angle * angle * (1 + OCEAN_MAX_SLOPE);
  for (const wave of OCEAN_WAVES) {
    const phaseRate = Math.abs(wave.x * dx + wave.z * dz + wave.speed * duration)
      + Math.hypot(wave.x, wave.z) * rotationReach;
    curvature += wave.amplitude * phaseRate * phaseRate;
  }

  const evaluate = (fraction: number) => {
    rotation.slerpQuaternions(q0, q1, fraction);
    const e = matrix.makeRotationFromQuaternion(rotation).elements;
    const px = plane.previous.x + dx * fraction;
    const py = plane.previous.y + dy * fraction;
    const pz = plane.previous.z + dz * fraction;
    const time = previousTime + duration * fraction;
    let gap = Infinity, vertex = 0;
    for (let i = 0; i < AIRFRAME_CONTACT_VERTICES.length; i += 3) {
      const x = AIRFRAME_CONTACT_VERTICES[i], y = AIRFRAME_CONTACT_VERTICES[i + 1], z = AIRFRAME_CONTACT_VERTICES[i + 2];
      const wx = px + e[0] * x + e[4] * y + e[8] * z;
      const wy = py + e[1] * x + e[5] * y + e[9] * z;
      const wz = pz + e[2] * x + e[6] * y + e[10] * z;
      const clearance = wy - oceanHeight(wx, wz, time);
      if (clearance < gap) { gap = clearance; vertex = i; }
    }
    return { gap, vertex };
  };
  type Sample = ReturnType<typeof evaluate>;
  const contact = (fraction: number, sample: Sample): SeaContact => {
    const i = sample.vertex;
    const point = new Vector3(AIRFRAME_CONTACT_VERTICES[i], AIRFRAME_CONTACT_VERTICES[i + 1], AIRFRAME_CONTACT_VERTICES[i + 2]);
    point.applyQuaternion(rotation.slerpQuaternions(q0, q1, fraction));
    point.add(plane.previous).addScaledVector(new Vector3(dx, dy, dz), fraction);
    const time = previousTime + duration * fraction;
    point.y = oceanHeight(point.x, point.z, time);
    return { time, fraction, point };
  };
  const search = (a: number, first: Sample, b: number, last: Sample, depth: number): SeaContact | null => {
    if (first.gap <= SEA_CONTACT_TOLERANCE) return contact(a, first);
    const width = b - a;
    // For every smooth vertex path, its chord error is <= M * width² / 8.
    // Taking the minimum across vertices preserves this lower bound.
    const bend = curvature * width * width / 8;
    if (Math.min(first.gap, last.gap) - bend > SEA_CONTACT_TOLERANCE) return null;
    if (depth === 24) {
      // At this bound the interval is < 6e-8 of a fixed tick; include a grazing
      // interval conservatively rather than tunnel through it. No time is lost.
      return contact(first.gap < last.gap ? a : b, first.gap < last.gap ? first : last);
    }
    const mid = (a + b) / 2, middle = evaluate(mid);
    return search(a, first, mid, middle, depth + 1) ?? search(mid, middle, b, last, depth + 1);
  };
  const first = evaluate(0);
  return search(0, first, 1, evaluate(1), 0);
}
