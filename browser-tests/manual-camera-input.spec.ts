import { expect, test } from '@playwright/test';
import { steerAndObserve } from './touch-command';
for (const mode of ['easy', 'normal'] as const) test(`${mode} held central pitch survives height resize and ends on release or rotation`,async({page,context})=>{
  await page.setViewportSize({width:402,height:874});await page.goto('/');
  await expect(page.locator('#start')).toBeEnabled();await page.locator(`input[value="${mode}"]`).check();await page.locator('#start').tap();
  const read=()=>page.evaluate(()=>(window as any).__kaisenReadState(false));
  const cdp=await context.newCDPSession(page),origin={x:180,y:500};
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{...origin,id:1}]});
  const accepted=await steerAndObserve(page,cdp,origin,0,.6);
  await page.waitForFunction(t=>(window as any).__kaisenReadState('clock').tick>=t,accepted.tick+45);
  const central=await steerAndObserve(page,cdp,origin,0,0);
  const centered=await read();
  await page.waitForFunction(t=>(window as any).__kaisenReadState('clock').tick>=t,central.tick+12);
  const held=await read();expect(held.player.pitch).toBeCloseTo(centered.player.pitch,7);
  const owner=held.controlsInput.steerPointer;expect(owner).not.toBeNull();
  await page.setViewportSize({width:402,height:820});
  expect((await read()).controlsInput.steerPointer).toBe(owner);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:origin.x,y:origin.y-54,id:1}]});
  const rebased=await read();expect(rebased.controlsInput.climb).toBeCloseTo(0,7);
  const moved=await steerAndObserve(page,cdp,{x:origin.x,y:origin.y-54},.3,0);
  expect(moved.turn).toBeCloseTo(.3,4);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  const released=await read();expect(released.controlsInput.steerPointer).toBeNull();
  await page.waitForFunction(t=>(window as any).__kaisenReadState('clock').tick>=t,released.tick+12);
  expect((await read()).player.pitch).toBeLessThan(held.player.pitch);
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{...origin,id:2}]});
  await page.setViewportSize({width:874,height:402});expect((await read()).controlsInput.steerPointer).toBeNull();
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await page.locator('#pause').tap();await page.locator('#pause-home').tap();
});
